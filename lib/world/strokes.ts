export function sampleStroke(stroke: Stroke, step = 3): Point[] {
  const points: Point[] = [stroke[0]];
  for (let i = 1; i < stroke.length; i++) {
    const a = stroke[i - 1],
      b = stroke[i],
      n = Math.ceil(Math.hypot(b[0] - a[0], b[1] - a[1]) / step);
    for (let j = 1; j <= n; j++)
      points.push([
        a[0] + ((b[0] - a[0]) * j) / n,
        a[1] + ((b[1] - a[1]) * j) / n,
      ]);
  }
  return points;
}
export const distance = (a: Point, b: Point) =>
  Math.hypot(a[0] - b[0], a[1] - b[1]);
export function follow(points: Point[], index: number, p: Point) {
  let next = index;
  for (let i = index; i < Math.min(points.length, index + 7); i++)
    if (distance(points[i], p) < 10) next = i + 1;
  return next;
}
